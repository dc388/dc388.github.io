# Abreviaturas latinas: se apartan antes de trocear, porque «i.e.» se partiría
# en «i» y «e» y ninguna de las dos es una palabra que haya que traducir.
ABREVIATURAS: dict[str, str] = {
    "i.e.": "es decir,",
    "i. e.": "es decir",
    "i.e": "es decir",
    "e.g.": "por ejemplo",
    "e. g.": "por ejemplo",
    "e.g": "por ejemplo",
    "cf.": "compárese",
    "viz.": "a saber",
    "etc.": "etc.",
}

_MARCA = re.compile(r"\|(?:inf|sus|adj)")
_PALABRA = re.compile(r"[A-Za-z][A-Za-z'’-]*")
_INGLESA = re.compile(r"[A-Za-z]")


def _trocear(texto: str) -> list[str]:
    """Parte en palabras y no-palabras, conservándolo todo."""
    piezas: list[str] = []
    ultimo = 0
    for m in _PALABRA.finditer(texto):
        if m.start() > ultimo:
            piezas.append(texto[ultimo:m.start()])
        piezas.append(m.group())
        ultimo = m.end()
    if ultimo < len(texto):
        piezas.append(texto[ultimo:])
    return piezas


def _clave(palabra: str) -> str:
    return palabra.lower().replace("’", "'")


_FRASES_POR_LARGO: list[tuple[int, dict[tuple[str, ...], str]]] = []


def _preparar() -> None:
    if _FRASES_POR_LARGO:
        return
    porlargo: dict[int, dict[tuple[str, ...], str]] = {}
    for ingles, espanol in FRASES.items():
        clave = tuple(_clave(p) for p in _PALABRA.findall(ingles))
        porlargo.setdefault(len(clave), {})[clave] = espanol
    for largo in sorted(porlargo, reverse=True):
        _FRASES_POR_LARGO.append((largo, porlargo[largo]))


def _es_nombre_propio(palabra: str) -> bool:
    """Un nombre propio de Strong: mayúscula inicial y no está en las tablas."""
    return palabra[:1].isupper()


def _sin_ligaduras(texto: str) -> str:
    """«dæmon» y «prætor» llevan ligadura, y el troceador sólo ve letras ASCII."""
    return (texto.replace("æ", "ae").replace("Æ", "Ae")
                 .replace("œ", "oe").replace("Œ", "Oe"))


def _gentilicio(palabra: str) -> str:
    """«Ashbelite» -> «ashbelita». Strong forma así casi todos los gentilicios,
    y dejarlos en inglés era lo que más cantaba en las entradas de nombres."""
    if palabra.endswith("ites") and len(palabra) > 6:
        return palabra[:-4].lower() + "itas"
    if palabra.endswith("ite") and len(palabra) > 5:
        return palabra[:-3].lower() + "ita"
    return palabra                       # cualquier otro nombre propio, tal cual


def traducir(texto: str | None) -> str | None:
    """Traduce una definición de Strong, o devuelve None si no la entiende."""
    if not texto or not texto.strip():
        return None
    _preparar()

    texto = _sin_ligaduras(texto)
    texto, apartadas = _apartar_abreviaturas(texto)
    piezas = _trocear(texto)
    # Índices de las piezas que son palabras, para casar frases sobre ellas.
    indices = [i for i, p in enumerate(piezas) if _PALABRA.fullmatch(p)]
    claves = [_clave(piezas[i]) for i in indices]

    salida: list[str] = []
    resuelto: list[bool] = [False] * len(piezas)
    puesto: list[str | None] = [None] * len(piezas)

    n = 0
    while n < len(indices):
        casado = False
        for largo, tabla in _FRASES_POR_LARGO:
            if n + largo > len(indices):
                continue
            # Sólo casa si entre esas palabras no hay puntuación fuerte.
            hueco = piezas[indices[n]:indices[n + largo - 1] + 1]
            if any(c in "".join(hueco) for c in ";:()[]{}"):
                continue
            if tuple(claves[n:n + largo]) in tabla:
                puesto[indices[n]] = tabla[tuple(claves[n:n + largo])]
                resuelto[indices[n]] = True
                for k in range(n + 1, n + largo):
                    puesto[indices[k]] = ""
                    resuelto[indices[k]] = True
                    # se traga también lo que hubiera entre medias
                    for j in range(indices[k - 1] + 1, indices[k]):
                        puesto[j] = ""
                        resuelto[j] = True
                n += largo
                casado = True
                break
        if casado:
            continue

        i = indices[n]
        palabra = piezas[i]
        clave = claves[n]
        if palabra in NOMBRES:
            puesto[i] = NOMBRES[palabra]
        elif clave in PALABRAS:
            puesto[i] = PALABRAS[clave]
        elif palabra.capitalize() in NOMBRES:
            puesto[i] = NOMBRES[palabra.capitalize()]
        elif _es_nombre_propio(palabra):
            puesto[i] = _gentilicio(palabra)
        else:
            return None                  # una sola palabra sin resolver y no hay traducción
        resuelto[i] = True
        n += 1

    for i, pieza in enumerate(piezas):
        salida.append(puesto[i] if resuelto[i] and puesto[i] is not None else pieza)

    return _restaurar(_ordenar(_limpiar("".join(salida))), apartadas)


_CENTINELA = "\ue000"


def _apartar_abreviaturas(texto: str) -> tuple[str, list[str]]:
    """Aparta «i.e.» y compañía para que el troceador no las parta."""
    apartadas: list[str] = []
    for abreviatura, espanol in ABREVIATURAS.items():
        while abreviatura in texto:
            texto = texto.replace(
                abreviatura, _CENTINELA + str(len(apartadas)) + _CENTINELA, 1)
            apartadas.append(espanol)
    return texto, apartadas


def _restaurar(texto: str, apartadas: list[str]) -> str:
    for n, espanol in enumerate(apartadas):
        texto = texto.replace(_CENTINELA + str(n) + _CENTINELA, espanol)
    return texto


def _limpiar(texto: str) -> str:
    texto = re.sub(r"[ \t]+", " ", texto)
    texto = re.sub(r" +([,;:.)\]])", r"\1", texto)
    texto = re.sub(r"([(\[]) +", r"\1", texto)
    texto = re.sub(r"\( *\)", "", texto)
    texto = re.sub(r" +", " ", texto)
    texto = re.sub(r"(^|[;,] *)(?:un|el) +(?=[;,]|$)", r"\1", texto)
    # las contracciones, que en español son obligatorias
    texto = re.sub(r"\bde el\b", "del", texto)
    texto = re.sub(r"\ba el\b", "al", texto)
    return texto.lstrip(" ,;").rstrip(" ")


