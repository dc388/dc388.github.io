def _nucleo(pieza: str) -> str:
    """La palabra desnuda: sin marca y sin la puntuación pegada."""
    return re.sub(r"[^0-9A-Za-zÀ-ÿ'-]", "", _MARCA.sub("", pieza)).lower()


def _femenino(sustantivo: str) -> bool:
    """El género del sustantivo, por su terminación; es lo que decide «un» o «una»."""
    nucleo = sustantivo.split()[0] if " " in sustantivo else sustantivo
    if nucleo in FEMENINOS:
        return True
    if nucleo in MASCULINOS_EN_A:
        return False
    if nucleo.endswith(_FINALES_FEMENINOS):
        return True
    return nucleo.endswith(("a", "as"))


def _plural(sustantivo: str) -> bool:
    nucleo = sustantivo.split()[0] if " " in sustantivo else sustantivo
    return (nucleo.endswith("s") and len(nucleo) > 3
            and nucleo not in SINGULARES_EN_S)


def _pluralizar(pieza: str) -> str:
    nucleo = _nucleo(pieza)
    if not nucleo or nucleo.endswith("s"):
        return pieza
    plural = nucleo + ("s" if nucleo[-1] in "aeiouáéíóú" else "es")
    if nucleo == "joven":
        plural = "jóvenes"                # el acento se mueve al pluralizar
    return pieza.replace(nucleo, plural, 1)


def _marca_de(pieza: str) -> str | None:
    hallada = _MARCA.search(pieza)
    return hallada.group()[1:] if hallada else None


def _ordenar(texto: str) -> str:
    """Pone la frase en español: infinitivo sin «a», adjetivo detrás del
    sustantivo y artículo concordado. Strong escribe en inglés lexicográfico y
    palabra por palabra saldría «un voz» y «un mudo bestia»."""
    piezas = texto.split(" ")

    # «to beget» -> «engendrar», no «a engendrar»
    sin_a: list[str] = []
    n = 0
    while n < len(piezas):
        if piezas[n] == "a" and n + 1 < len(piezas) and _marca_de(piezas[n + 1]) == "inf":
            n += 1
            continue
        sin_a.append(piezas[n])
        n += 1
    piezas = sin_a

    # el adjetivo, detrás; la puntuación que cerraba el grupo se queda al final
    n = 0
    while n + 1 < len(piezas):
        if _marca_de(piezas[n]) == "adj" and _marca_de(piezas[n + 1]) == "sus":
            adjetivo, sustantivo = piezas[n], piezas[n + 1]
            cola = re.search(r"[^0-9A-Za-zÀ-ÿ'-]*$", _MARCA.sub("", sustantivo)).group()
            if cola:
                sustantivo = sustantivo[: len(sustantivo) - len(cola)]
            if _plural(_nucleo(sustantivo)):
                adjetivo = _pluralizar(adjetivo)
            piezas[n], piezas[n + 1] = sustantivo, adjetivo + cola
            n += 2
            continue
        n += 1

    # concordancia: el determinante y el adjetivo, con el sustantivo
    for n, pieza in enumerate(piezas):
        if _marca_de(pieza) != "sus":
            continue
        nucleo = _nucleo(pieza)
        if not nucleo or not _femenino(nucleo):
            continue
        if n and _nucleo(piezas[n - 1]) in DETERMINANTES and nucleo not in FEMENINOS_CON_EL:
            anterior = _nucleo(piezas[n - 1])
            piezas[n - 1] = piezas[n - 1].replace(anterior, DETERMINANTES[anterior], 1)
        if n + 1 < len(piezas) and _marca_de(piezas[n + 1]) == "adj":
            siguiente = _nucleo(piezas[n + 1])
            if siguiente.endswith("o"):
                piezas[n + 1] = piezas[n + 1].replace(siguiente, siguiente[:-1] + "a", 1)

    return _MARCA.sub("", " ".join(piezas))


def desconocidas(texto: str) -> list[str]:
    """Las palabras que impiden traducir esta entrada. Para afinar las tablas."""
    _preparar()
    if traducir(texto) is not None:
        return []
    faltan = []
    texto, _ = _apartar_abreviaturas(_sin_ligaduras(texto))
    for palabra in _PALABRA.findall(texto):
        if (palabra not in NOMBRES and _clave(palabra) not in PALABRAS
                and not _es_nombre_propio(palabra)):
            faltan.append(_clave(palabra))
    return faltan
